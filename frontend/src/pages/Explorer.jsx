import { Button } from "@/components/ui/button";
import { PageHeader, Panel, KV, Empty, SimTag, StatusPill } from "@/components/common";
import { useTx } from "@/context/TxContext";
import { useAuth } from "@/context/AuthContext";
import { ethFmt, dt } from "@/lib/fmt";

const Confirmations = ({ n, required = 12 }) => (
  <div data-testid="confirmation-tracker">
    <div className="mb-2 flex items-center justify-between">
      <span className="eyebrow">Simulated confirmations</span>
      <span data-testid="confirmation-count" className="font-mono text-sm text-white">{n}/{required}</span>
    </div>
    <div className="grid grid-cols-12 gap-1.5">
      {Array.from({ length: required }).map((_, i) => (
        <div key={i} className={`h-8 rounded-sm border transition-all duration-500 ${i < n ? "border-sky-400/70 bg-sky-400/80 shadow-[0_0_12px_rgba(56,189,248,0.45)]" : i === n ? "pulse-ring border-sky-400/40 bg-sky-400/10" : "border-[#26354D] bg-[#0B111E]"}`} />
      ))}
    </div>
  </div>
);

const Analysis = ({ an }) => (
  <Panel title="Simulated blockchain analysis" sub={an.provider} testid="analysis-panel" actions={<SimTag>Fictional</SimTag>}>
    <div className="mb-4 flex items-end gap-4">
      <div className="font-mono text-4xl font-semibold text-emerald-300" data-testid="analysis-risk-score">{an.risk_score}<span className="text-base text-slate-500">/100</span></div>
      <StatusPill status={an.risk_band} />
    </div>
    <KV label="Hops analysed" value={an.hops_analysed} mono />
    <KV label="Counterparties traced (fictional)" value={an.counterparties_traced} mono />
    <KV label="Generated" value={dt(an.generated_at)} />
    <div className="mt-4 space-y-2.5">
      {an.exposure.map((e) => (
        <div key={e.category}>
          <div className="flex justify-between text-xs text-slate-300"><span>{e.category}</span><span className="font-mono">{e.percent}%</span></div>
          <div className="mt-1 h-1.5 rounded-full bg-[#0B111E]"><div className="h-full rounded-full bg-gradient-to-r from-sky-500 to-sky-300" style={{ width: `${e.percent}%` }} /></div>
        </div>
      ))}
    </div>
  </Panel>
);

export default function Explorer() {
  const { tx, act } = useTx();
  const { user } = useAuth();
  const dep = tx.deposit;
  const st = tx.settlement;
  return (
    <div data-testid="explorer-page">
      <PageHeader eyebrow="Blockchain Explorer" title="Simulated network monitor" desc="Ethereum-style view of fictional data. None of these hashes, addresses or blocks exist on Ethereum and they cannot be verified on any block explorer."
        actions={user.role === "admin" && tx.current_step === 13 && <Button data-testid="explorer-generate-analysis" onClick={() => act("generate_analysis", {}, "Simulated blockchain analysis generated")}>Generate blockchain analysis</Button>} />
      <div className="mb-6 rounded-md border border-red-500/30 bg-red-500/5 px-4 py-3 font-mono text-xs text-red-200" data-testid="explorer-disclaimer">
        FICTIONAL TRANSACTION DATA — NOT BROADCAST TO, RECORDED ON, OR VERIFIABLE ON THE ETHEREUM NETWORK
      </div>
      <div className="grid gap-6 xl:grid-cols-[1.4fr_1fr]">
        <Panel title="Simulated ETH deposit" testid="deposit-panel" actions={dep.initiated_at && <StatusPill status={dep.confirmations >= 12 ? "Confirmed (simulated)" : "Confirming (simulated)"} testid="deposit-status" />}>
          {!dep.initiated_at ? <Empty testid="deposit-empty">No simulated deposit yet. The sender initiates it at step 11.</Empty> : (
            <>
              <Confirmations n={dep.confirmations} />
              <div className="mt-5">
                <KV label="Simulated sending address" value={dep.from_address} mono sim testid="deposit-from" />
                <KV label="Simulated receiving address" value={dep.to_address} mono sim testid="deposit-to" />
                <KV label="Simulated ETH quantity" value={ethFmt(dep.eth_quantity, 6)} mono sim testid="deposit-qty" />
                <KV label="Simulated transaction hash" value={dep.tx_hash} mono sim testid="deposit-hash" />
                <KV label="Simulated block number" value={dep.block_number?.toLocaleString()} mono sim testid="deposit-block" />
                <KV label="Simulated network fee" value={ethFmt(dep.network_fee_eth, 6)} mono sim testid="deposit-fee" />
                <KV label="Simulated gas used" value={dep.gas_used?.toLocaleString()} mono />
                <KV label="Simulated timestamp" value={dt(dep.initiated_at)} mono sim testid="deposit-timestamp" />
              </div>
            </>
          )}
        </Panel>
        {tx.analysis.generated_at ? <Analysis an={tx.analysis} /> : <Panel title="Simulated blockchain analysis"><Empty testid="analysis-empty">Generated by the administrator after 12/12 simulated confirmations.</Empty></Panel>}
      </div>
      {st.release_tx_hash && (
        <Panel title="Simulated release transaction" className="mt-6" testid="release-panel">
          <KV label="From (simulated escrow)" value={tx.escrow_vault_address} mono sim />
          <KV label="To (simulated recipient wallet)" value={tx.onboarding.recipient.data.wallet_address} mono sim />
          <KV label="Simulated release hash" value={st.release_tx_hash} mono sim testid="release-hash" />
          <KV label="Simulated block" value={st.release_block?.toLocaleString()} mono sim />
          <KV label="Quantity" value={ethFmt(st.release_eth, 6)} mono sim />
        </Panel>
      )}
    </div>
  );
}
